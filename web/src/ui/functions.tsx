import type { Command } from "../core/command";
import { fn } from "../core/command";
import { Empty } from "./components";
import { Description } from "./functions/Description";
import { PriceChart } from "./functions/PriceChart";
import { Monitor } from "./functions/Monitor";
import { QuoteBoard, Movers, Heatmap } from "./functions/Boards";
import { News } from "./functions/News";
import { SecurityFinder } from "./functions/SecurityFinder";
import { Depth, TimeAndSales } from "./functions/Crypto";
import { Help } from "./functions/Help";
import { Financials, Events, Dividends, EarningsCalendar } from "./functions/Company";
import { History, Beta, Factors, EventStudyView, Backtest, Compare, Optimizer, Correlation, Screener } from "./functions/Research";
import { Economy, WorldEconomy } from "./functions/Economy";
import { Ticket, Portfolio, Blotter, Alerts } from "./functions/Trading";
import { Settings, Pro } from "./functions/Settings";
import { OptionMonitor, OptionStrategy } from "./functions/Options";
import { RelativeValuation } from "./functions/Valuation";
import { Seasonality } from "./functions/Seasonality";
import { BondCalculator, YieldCurve } from "./functions/Bonds";
import { Learn } from "./functions/Learn";
import { DCF } from "./functions/DCF";
import { AIAnalyst } from "./functions/AI";
import { DataSources } from "./functions/DataSources";
import { commodityGroups, currencyGroups, indices, rates, isStreaming } from "../core/universe";
import { market } from "../data/market";
import { useStore } from "../data/store";

export function FunctionView({ panel, cmd }: { panel: number; cmd: Command }) {
  useStore(market);
  const i = cmd.instrument;
  if (i && market.unknown.has(i.symbol)) return <Empty title={`${i.ticker}: security not found`} detail="No market data exists for this ticker. Check the symbol, or search with SECF." />;
  switch (cmd.fn) {
    case "DES": return <Description panel={panel} i={i!} />;
    case "GP": return <PriceChart key={i!.symbol} i={i!} />;
    case "W": return <Monitor panel={panel} />;
    case "WEI": return <QuoteBoard panel={panel} groups={(["AMERICAS", "EMEA", "ASIA/PACIFIC"] as const).map((r) => [r, indices.filter((x) => x.region === r)])} />;
    case "FX": return <QuoteBoard panel={panel} groups={currencyGroups()} />;
    case "COMD": return <QuoteBoard panel={panel} groups={commodityGroups()} />;
    case "RATES": return <QuoteBoard panel={panel} groups={[["US TREASURY YIELDS", rates]]} yields />;
    case "MOST": return <Movers panel={panel} />;
    case "HMAP": return <Heatmap panel={panel} />;
    case "TOP": return <News />;
    case "CN": return <News i={i} />;
    case "SECF": return <SecurityFinder panel={panel} initial={cmd.query} />;
    case "DEPTH": return isStreaming(i!) ? <Depth i={i!} /> : <Empty title="Depth is for live crypto" detail="Order books stream for Coinbase coins: try BTC DEPTH." />;
    case "TAS": return isStreaming(i!) ? <TimeAndSales i={i!} /> : <Empty title="Time & sales is for live crypto" detail="Trades stream for Coinbase coins: try ETH TAS." />;
    case "HELP": return <Help panel={panel} />;
    case "FA": return <Financials key={i!.symbol} i={i!} />;
    case "EVTS": return <Events key={i!.symbol} i={i!} />;
    case "DVD": return <Dividends key={i!.symbol} i={i!} />;
    case "ERN": return <EarningsCalendar panel={panel} />;
    case "HP": return <History key={i!.symbol} i={i!} />;
    case "BETA": return <Beta key={i!.symbol} i={i!} />;
    case "FACT": return <Factors key={i!.symbol} i={i!} />;
    case "EVST": return <EventStudyView key={i!.symbol} i={i!} panel={panel} />;
    case "BT": return <Backtest key={i!.symbol} i={i!} />;
    case "COMP": return <Compare panel={panel} />;
    case "MVO": return <Optimizer panel={panel} />;
    case "CORR": return <Correlation panel={panel} />;
    case "EQS": return <Screener panel={panel} />;
    case "ECO": return <Economy />;
    case "TRADE": return <Ticket key={`${i!.symbol}|${cmd.side}`} i={i!} side={cmd.side} />;
    case "PORT": return <Portfolio panel={panel} />;
    case "BLOT": return <Blotter />;
    case "PREF": return <Settings />;
    case "RV": return <RelativeValuation key={i!.symbol} i={i!} panel={panel} />;
    case "SEAS": return <Seasonality key={i!.symbol} i={i!} />;
    case "GC": return <YieldCurve />;
    case "YAS": return <BondCalculator />;
    case "LEARN": return <Learn panel={panel} />;
    case "DCF": return <DCF key={i!.symbol} i={i!} />;
    case "AI": return <AIAnalyst key={i!.symbol} i={i!} />;
    case "DATA": return <DataSources />;
    case "OMON": return <OptionMonitor key={i!.symbol} i={i!} panel={panel} />;
    case "OSA": return <OptionStrategy key={i!.symbol} i={i!} />;
    case "PRO": return <Pro />;
    case "ALRT": return <Alerts key={i?.symbol} i={i} panel={panel} />;
    case "ECST": return <WorldEconomy key={cmd.query ?? ""} query={cmd.query} />;
  }
  return <Empty title={`${cmd.fn} is coming to the web`} detail={`${fn(cmd.fn).title} works in the Kestrel app for iPad and Mac and arrives on the web in the next phase.`} />;
}
