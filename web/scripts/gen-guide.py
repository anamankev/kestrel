"""Generates src/core/guide.generated.ts from KestrelCore/Guide.swift (topics, how-tos, glossary)."""
import re, sys, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "KestrelCore/Sources/KestrelCore/Guide.swift").read_text()

def block(name):
    i = src.index(f"public static let {name}")
    j = src.index("=", i) + 1
    while src[j] != "[": j += 1
    depth, k, s = 0, j, False
    while True:
        c = src[k]
        if s:
            if c == "\\": k += 2; continue
            if c == '"': s = False
        elif c == '"': s = True
        elif c in "[(": depth += 1
        elif c in "])":
            depth -= 1
            if depth == 0: return src[j:k + 1]
        k += 1

def convert(text):
    out, stack, s, k = [], [], False, 0
    while k < len(text):
        c = text[k]
        if s:
            out.append(c)
            if c == "\\": out.append(text[k + 1]); k += 2; continue
            if c == '"': s = False
            k += 1; continue
        if c == '"': s = True; out.append(c); k += 1; continue
        if text.startswith(".init(", k): out.append("{ "); stack.append("}"); k += 6; continue
        if text.startswith("HowTo(", k): out.append("{ "); stack.append("}"); k += 6; continue
        if c == "(": stack.append(")"); out.append(c); k += 1; continue
        if c == "[": stack.append("]"); out.append(c); k += 1; continue
        if c in ")]": out.append(" " + stack.pop() if stack[-1] == "}" else stack.pop()); k += 1; continue
        m = re.match(r"function: \.(\w+)", text[k:])
        if m: out.append(f'function: "{m.group(1).upper()}"'); k += m.end(); continue
        out.append(c); k += 1
    return "".join(out)

topics = convert(block("topics"))
howtos = convert(block("howTos"))
gloss = block("glossary")
pairs = re.findall(r'"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"', gloss)
home_src = src[src.index("static let glossaryHome"):]
home_src = home_src[:home_src.index("]") + 1]
home = re.findall(r'"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"', home_src)
obj = lambda ps: "{\n" + "".join(f'  "{k}": "{v}",\n' for k, v in ps) + "}"
out = f"""// Generated by scripts/gen-guide.py from KestrelCore/Guide.swift. Do not edit.
import type {{ Topic, HowTo }} from "./guide";
export const topics: Topic[] = {topics};
export const howTos: HowTo[] = {howtos};
export const glossary: Record<string, string> = {obj(pairs)};
export const glossaryHome: Record<string, string> = {obj(home)};
"""
(root / "web/src/core/guide.generated.ts").write_text(out)
print(len(pairs), "terms,", topics.count("function:"), "topics,", howtos.count("title:"), "how-tos")
